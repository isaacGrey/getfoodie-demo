const test=require("node:test");
const assert=require("node:assert/strict");
const C=require("../core.js");
const make=()=>C.seed();
const as=(s,role)=>{const a=C.CREDENTIALS.find(x=>x.role===role);return C.login(s,a.email,a.password);};
test("sample credentials require the correct password and respect disabled users",()=>{
 const s=make();
 assert.throws(()=>C.login(s,"customer@demo.getfoodie.app","wrong"),/Incorrect/);
 const admin=as(s,"admin"),customer=as(s,"customer");
 assert.equal(customer.role,"customer");
 C.setAccountEnabled(s,admin,"c1",false);
 assert.throws(()=>as(s,"customer"),/disabled/);
 C.setAccountEnabled(s,admin,"c1",true);
 assert.equal(as(s,"customer").id,"c1");
 assert.throws(()=>C.setAccountEnabled(s,admin,"a1",false),/cannot/);
});
test("browser-local state persists with a versioned data model",()=>{
 const s=make(),memory=new Map();
 const store={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)};
 C.save(store,s);
 assert.equal(C.load(store).version,2);
 assert.equal(C.load(store).menu.length,s.menu.length);
 assert.equal(C.load({getItem:()=>"{invalid"}).version,2);
});
test("customer -> checkout -> vendor fulfilment -> review",()=>{
 const s=make(),customer=as(s,"customer"),vendor=as(s,"vendor");
 const start=C.item(s,1).stock;
 C.addToCart(s,customer,1,2);
 C.addToCart(s,customer,3,1);
 assert.equal(C.cartInfo(s,customer).subtotal,507);
 const o=C.checkout(s,customer,{fulfilment:"Delivery",address:"18 Fictional Street, Makati",notes:"No utensils"});
 assert.equal(o.id,"GF-1003");
 assert.equal(o.total,536);
 assert.equal(o.paymentStatus,"Unpaid");
 assert.equal(C.item(s,1).stock,start-2);
 assert.equal(C.getCart(s,customer).length,0);
 assert.equal(C.vendorOrder(s,vendor,o.id).status,"Placed");
 for(const step of ["Accepted","Preparing","Ready"])C.transition(s,vendor,o.id,step);
 assert.throws(()=>C.transition(s,vendor,o.id,"Out for delivery"),/Assign/);
 C.assignDriver(s,vendor,o.id,{name:"Sample Courier",phone:"09990000111"});
 for(const step of ["Out for delivery","Delivered"])C.transition(s,vendor,o.id,step);
 assert.equal(o.driver.name,"Sample Courier");
 assert.equal(o.status,"Delivered");
 assert.equal(o.paymentStatus,"Collected");
 assert.equal(o.history.length,6);
 C.rateOrder(s,customer,o.id,5);
 assert.equal(o.rating,5);
 assert.throws(()=>C.requestCancel(s,customer,o.id),/cannot|no longer/);
});
test("a vendor resolves pre-acceptance cancellation and restores stock",()=>{
 const s=make(),customer=as(s,"customer"),vendor=as(s,"vendor");
 const start=C.item(s,2).stock;
 C.addToCart(s,customer,2,1);
 const o=C.checkout(s,customer,{fulfilment:"Pickup",address:""});
 assert.equal(o.deliveryFee,0);
 C.requestCancel(s,customer,o.id);
 assert.equal(o.cancelRequested,true);
 assert.throws(()=>C.transition(s,vendor,o.id,"Accepted"),/cancellation/);
 C.transition(s,vendor,o.id,"Cancelled");
 assert.equal(o.status,"Cancelled");
 assert.equal(C.item(s,2).stock,start);
 assert.equal(o.cancelRequested,false);
});
test("vendor handles rejections, cancellation decisions, delivery and pickup branches",()=>{
 const s=make(),customer=as(s,"customer"),vendor=as(s,"vendor");
 C.addToCart(s,customer,1);
 const rejected=C.checkout(s,customer,{fulfilment:"Delivery",address:"10 Sample Ave"});
 assert.throws(()=>C.transition(s,vendor,rejected.id,"Rejected"),/reason/);
 C.transition(s,vendor,rejected.id,"Rejected","Kitchen unavailable");
 assert.equal(rejected.history.at(-1).reason,"Kitchen unavailable");
 assert.equal(C.item(s,1).stock,26);
 C.addToCart(s,customer,1);
 const pickup=C.checkout(s,customer,{fulfilment:"Pickup"});
 for(const status of ["Accepted","Preparing","Ready","Delivered"])C.transition(s,vendor,pickup.id,status);
 assert.equal(pickup.status,"Delivered");
 assert.ok(!pickup.history.some(x=>x.status==="Out for delivery"));
 C.addToCart(s,customer,1);
 const another=C.checkout(s,customer,{fulfilment:"Delivery",address:"11 Test Road"});
 C.requestCancel(s,customer,another.id);
 C.declineCancel(s,vendor,another.id);
 assert.equal(another.cancelRequested,false);
 C.transition(s,vendor,another.id,"Accepted");
});
test("cart enforces restaurant isolation, availability and limits",()=>{
 const s=make(),customer=as(s,"customer"),admin=as(s,"admin");
 C.addToCart(s,customer,1);
 assert.throws(()=>C.addToCart(s,customer,5),/one restaurant/);
 assert.throws(()=>C.addToCart(s,customer,1,50),/Invalid quantity/);
 C.setQty(s,customer,1,0);
 assert.equal(C.getCart(s,customer).length,0);
 C.adminRestaurant(s,admin,"r1","Suspended");
 assert.throws(()=>C.addToCart(s,customer,1),/unavailable/);
});
